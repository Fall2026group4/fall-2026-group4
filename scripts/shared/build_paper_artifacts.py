    ax.set_xticks(range(3), lab)
    ax.set(ylabel='$T_{rec}/T_{full}$', ylim=(0, 1.1), title='M4: causal effect carried by the SAE reconstruction')
    ax.legend(frameon=False, fontsize=7, ncol=3)
    ax.grid(axis='y', alpha=.3)
    savefig(fig, 'fig_m4_preservation')


