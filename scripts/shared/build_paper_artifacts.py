#!/usr/bin/env python3
"""Build the paper's LaTeX tables and vector figures directly from committed result files.

Every number in research_paper/Latex/tables/*.tex and every figure in research_paper/Latex_Fig/*.{pdf,svg} is read
from the CSV/JSON files named in SOURCES below; nothing is typed by hand. Re-running regenerates them (tables and
figures are derived artifacts, so overwriting them is intended; no result file is ever written).

Run from the repository root:
    python scripts/shared/build_paper_artifacts.py
"""
import json
import logging
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
TAB = REPO / 'research_paper/Latex/tables'
FIG = REPO / 'research_paper/Latex_Fig'
log = logging.getLogger('paper')

SOURCES = {
    'recon': 'results/openwebtext/reconstruction_evaluation/uninterrupted_protocol/all_layers_summary.csv',
    'splice': 'results/openwebtext/spliced_evaluation/summary.csv',
    'm0': 'results/shared/m0_within_layer_reanalysis/within_layer_regressions.csv',
    'm0_arch': 'results/shared/m0_within_layer_reanalysis/architecture_by_layer.csv',
    'm1': 'results/repe/repe_lm_gates/gates.json',
    'm2': 'results/shared/m2_four_level_faithfulness/summary_by_layer_arch.csv',
    'm3': 'results/repe/causal_site_sweep/cells_validation.csv',
    'm4': 'results/repe/sae_patch_decomposition/architecture_summary.csv',
    'method_a': 'results/geometry_of_truth/method_a_layer6/summary.csv',
    'e2e': 'results/geometry_of_truth/e2e_inspired_layer6/summary.csv',
}
ARCHS = ['relu', 'topk', 'jumprelu']
ANAME = {'relu': 'ReLU', 'topk': 'TopK', 'jumprelu': 'JumpReLU'}
COLORS = {'relu': '#1b6ca8', 'topk': '#d1495b', 'jumprelu': '#2e933c'}


def read(key):
    p = REPO / SOURCES[key]
    return json.loads(p.read_text()) if p.suffix == '.json' else pd.read_csv(p)


def write_table(name, body, caption, label, source_keys, colspec):
    src = '; '.join(f'\\texttt{{{SOURCES[k].replace("_", chr(92) + "_")}}}' for k in source_keys)
    tex = (f'% generated by scripts/shared/build_paper_artifacts.py from {", ".join(SOURCES[k] for k in source_keys)}\n'
           f'\\begin{{table}}[t]\n\\centering\n\\small\n\\caption{{{caption} Source: {src}.}}\n\\label{{{label}}}\n'
           f'\\begin{{adjustbox}}{{max width=\\linewidth}}\n\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{body}\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{table}}\n')
    (TAB / f'{name}.tex').write_text(tex)
    log.info('table %s', name)


def savefig(fig, name):
    for ext in ('pdf', 'svg'):
        fig.savefig(FIG / f'{name}.{ext}', bbox_inches='tight')
    plt.close(fig)
    log.info('figure %s', name)


def f3(x):
    return f'{x:.3f}'


# ---------------------------------------------------------------------------------------------------------- tables
def table_reconstruction():
    d = read('recon').set_index(['layer', 'architecture'])
    rows = ''
    for L in range(12):
        ev = ' & '.join(f'{d.loc[(L, a), "ev_mean"]:.3f}$\\pm${d.loc[(L, a), "ev_sd"]:.3f}' for a in ARCHS)
        l0 = ' & '.join(f'{d.loc[(L, a), "l0_mean"]:.1f}' for a in ARCHS)
        rows += f'{L} & {ev} & {l0} \\\\\n'
    head = ('Layer & \\multicolumn{3}{c}{OWT test EV (mean$\\pm$sd, 3 seeds)} & \\multicolumn{3}{c}{OWT test L0} \\\\\n'
            '\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n & ReLU & TopK & JumpReLU & ReLU & TopK & JumpReLU \\\\\n\\midrule\n')
    write_table('t_reconstruction', head + rows,
                'Reconstruction on the OWT test split (TEST; 12{,}700 tokens), width 3072, target L0 = 128. Layer-0 '
                'JumpReLU includes the unmatched seed 42 (L0 73.6).', 'tab:recon', ['recon'], 'rcccccc')


def table_splice():
    d = read('splice').set_index(['layer', 'architecture'])
    rows = ''
    for L in range(12):
        dce = ' & '.join(f3(d.loc[(L, a), 'owt__delta_ce_mean']) for a in ARCHS)
        lr = ' & '.join(f3(d.loc[(L, a), 'owt__loss_recovered_mean']) for a in ARCHS)
        rows += f'{L} & {dce} & {lr} \\\\\n'
    head = ('Layer & \\multicolumn{3}{c}{Spliced $\\Delta$CE (nats/token, $\\downarrow$)} & \\multicolumn{3}{c}{Loss recovered ($\\uparrow$)} \\\\\n'
            '\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n & ReLU & TopK & JumpReLU & ReLU & TopK & JumpReLU \\\\\n\\midrule\n')
    write_table('t_splice', head + rows,
                'Behavioural faithfulness: GPT-2 with the SAE reconstruction spliced in at every non-BOS position '
                '(OWT validation; original CE 3.396 nats/token; matched seeds only).', 'tab:splice', ['splice'], 'rcccccc')


def table_m0():
    d = read('m0')
    d = d[d.holm_family.astype(str) == 'True']
    names = {'log_owt_nmse': 'log OWT NMSE', 'log_got_rel_err': 'log GoT relative error',
             'got_logistic_gap': 'GoT frozen-logistic gap', 'owt_delta_ce': 'OWT spliced $\\Delta$CE'}
    rows = ''
    for r in d.itertuples():
        rows += (f'{names.get(r.predictor, r.predictor)} $\\rightarrow$ {names.get(r.outcome, r.outcome)} & {r.beta:.3f} & '
                 f'[{r.ci95_low:.3f}, {r.ci95_high:.3f}] & {r.p_perm:.4f} & {r.p_holm:.4f} & {r.n} \\\\\n')
    head = 'Predictor $\\rightarrow$ outcome & $\\beta$ & 95\\% CI & $p_{\\text{perm}}$ & $p_{\\text{Holm}}$ & $n$ \\\\\n\\midrule\n'
    write_table('t_m0', head + rows,
                'M0 within-layer regressions (VALIDATION): outcome $\\sim\\beta\\cdot$predictor + layer FE + architecture '
                'FE + log L0, Freedman--Lane permutation within layer. The GoT row passes formally but vanishes without '
                'architecture fixed effects ($p=0.89$; see text).', 'tab:m0', ['m0'], 'lccccc')


def m2_means():
    d = read('m2')
    info = {'got_cities': range(4, 12), 'repe_persona': range(1, 12), 'repe_neutral': range(1, 12)}
    out = {}
    for t, Ls in info.items():
        s = d[(d.task == t) & d.layer.isin(list(Ls))]
        for a in ARCHS:
            x = s[s.architecture == a]
            out[(t, a)] = {k: x[k].mean() for k in ('frozen_logistic_gap_mean', 'noise_frozen_logistic_gap_mean',
                                                   'frozen_massmean_gap_mean', 'refit_logistic_gap_mean',
                                                   'pca_refit_logistic_gap', 'refit_mlp_gap_mean', 'error_term_auroc_mean')}
    return out


def table_m2():
    m = m2_means()
    tname = {'got_cities': 'GoT', 'repe_persona': 'Persona', 'repe_neutral': 'Neutral'}
    rows = ''
    for t in tname:
        for a in ARCHS:
            v = m[(t, a)]
            rows += (f'{tname[t]} & {ANAME[a]} & {f3(v["frozen_logistic_gap_mean"])} & {f3(v["noise_frozen_logistic_gap_mean"])} & '
                     f'{f3(v["frozen_massmean_gap_mean"])} & {f3(v["refit_logistic_gap_mean"])} & {f3(v["pca_refit_logistic_gap"])} & '
                     f'{f3(v["refit_mlp_gap_mean"])} & {f3(v["error_term_auroc_mean"])} \\\\\n')
        rows += '\\midrule\n' if t != 'repe_neutral' else ''
    head = ('Task & SAE & Frozen log. & Noise & Frozen m.-mean & Re-trained log. & PCA re-tr. & MLP & Error AUROC \\\\\n\\midrule\n')
    write_table('t_m2', head + rows,
                'M2 information preservation (VALIDATION): AUROC gaps (original $-$ reconstructed; $\\downarrow$), mean '
                'over informative layers (GoT 4--11, RepE-LM 1--11) and 3 seeds. ``Noise'' adds isotropic noise with the '
                'norm of the SAE error; ``PCA'' is matched to the SAE\'s OWT validation NMSE. Error AUROC: label decoded '
                'from the error term alone.', 'tab:m2', ['m2'], 'llccccccc')


