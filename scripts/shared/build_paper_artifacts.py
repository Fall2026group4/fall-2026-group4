#!/usr/bin/env python3
"""Build the paper's LaTeX tables and vector figures directly from committed result files.

Every number in research_paper/Latex/tables/*.tex and every figure in research_paper/Latex_Fig/*.{pdf,svg} is read
from the CSV/JSON files named in SOURCES below; nothing is typed by hand. Re-running regenerates them (tables and
figures are derived artifacts, so overwriting them is intended; no result file is ever written).

Run from the repository root:
    python scripts/shared/build_paper_artifacts.py
"""
