def read(key):
    p = REPO / SOURCES[key]
    return json.loads(p.read_text()) if p.suffix == '.json' else pd.read_csv(p)


def write_table(name, body, caption, label, source_keys, colspec):
    src = '; '.join(f'\\texttt{{{SOURCES[k].replace("_", chr(92) + "_")}}}' for k in source_keys)
    tex = (f'% generated by scripts/shared/build_paper_artifacts.py from {", ".join(SOURCES[k] for k in source_keys)}\n'
           f'\\begin{{table}}[t]\n\\centering\n\\small\n\\caption{{{caption} Source: {src}.}}\n\\label{{{label}}}\n'
           f'\\begin{{adjustbox}}{{max width=\\linewidth}}\n\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{body}\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{table}}\n')
    (TAB / f'{name}.tex').write_text(tex)
    log.info('table %s', name)


def savefig(fig, name):
    # fixed metadata and SVG hash salt so regenerated figures are byte-identical (reviewers can diff them)
    fig.savefig(FIG / f'{name}.pdf', bbox_inches='tight', metadata={'CreationDate': None, 'ModDate': None})
    fig.savefig(FIG / f'{name}.svg', bbox_inches='tight', metadata={'Date': None})
    plt.close(fig)
    log.info('figure %s', name)


def f3(x):
    return f'{x:.3f}'


