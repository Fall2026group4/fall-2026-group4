"""Post-hoc multiplicity check and paper table for PCA-CM (capacity-matched PCA).

Evidence level: descriptive re-analysis of committed VALIDATION outputs. Reads only
`results/shared/pca_capacity_matched/{got_paired,decisions}.csv`; no model, checkpoint,
cache or test row is read, and nothing is re-run.

Why: the pre-registered PCA-CM rule calls a family x layer x reference cell "SAE BETTER"
when every seed's paired 95 % grouped-bootstrap CI of (SAE gap - PCA gap) lies below 0.
That is a per-cell, nominal-level rule with no correction across cells. Before the paper
may say "significantly better", this script checks how many of those cells survive a
family-wise correction.

Method (approximate, stated as such in the outputs):
* per seed, SE = (CI high - CI low) / 3.92 and z = diff / SE (normal approximation to the
  stored percentile bootstrap CI); two-sided p = 2 * (1 - Phi(|z|));
* a cell is "better" only if every seed rejects (intersection-union test), so the cell
  p-value is the largest per-seed p among seeds whose difference is negative;
* Holm correction over all trained-SAE cells of the two capacity-matched references
  (`capacity_k128`, `task_l0_matched`; 20 cells each = 40), alpha = 0.05.

The random-decoder control is excluded, as in the PCA-CM family counts.
Outputs refuse to be overwritten.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results/shared/pca_capacity_matched"
OUT = SRC / "posthoc_multiplicity"
TABLE = ROOT / "research_paper/Latex/tables/t_pcacm.tex"
REFS = ("capacity_k128", "task_l0_matched")
ALPHA = 0.05
log = logging.getLogger("pca_cm_posthoc")

LABEL = {
    ("old", "relu"): "old ReLU-3072", ("old", "topk"): "old TopK-3072",
    ("old", "jumprelu"): "old JumpReLU-3072", ("r2", "topk"): "R2 TopK",
    ("r2", "batchtopk"): "R2 BatchTopK", ("r2", "relu"): "R2 ReLU",
    ("r2", "topk_w3072"): "R2 TopK-3072", ("r4_kl", "topk"): "R4 KL",
    ("r4_mse", "topk"): "R4 MSE", ("resjb", "resjb_relu_24576"): "res-jb",
}


def holm(p: np.ndarray, alpha: float = ALPHA) -> np.ndarray:
    order = np.argsort(p)
    m = len(p)
    reject = np.zeros(m, dtype=bool)
    for i, ix in enumerate(order):
        if p[ix] <= alpha / (m - i):
            reject[ix] = True
        else:
            break
    return reject


def cell_table() -> pd.DataFrame:
    p = pd.read_csv(SRC / "got_paired.csv")
    p = p[(p.name != "topk_frozen_decoder") & p.reference.isin(REFS)].copy()
    se = (p.diff_refit_logistic_gap_ci_high - p.diff_refit_logistic_gap_ci_low) / 3.92
    p["z"] = p.diff_refit_logistic_gap / se
    p["p_two_sided"] = 2 * norm.sf(p.z.abs())
    keys = ["layer", "family", "name", "reference"]
    g = p.groupby(keys)
    cells = g.agg(n_seeds=("seed", "count"), diff_mean=("diff_refit_logistic_gap", "mean"),
                  z_weakest=("z", "max"), ci_high_max=("diff_refit_logistic_gap_ci_high", "max"),
                  ci_low_min=("diff_refit_logistic_gap_ci_low", "min")).reset_index()
    # intersection-union: the cell rejects "SAE not better" only if every seed does
    cells["p_cell"] = np.where(cells.z_weakest < 0, 2 * norm.sf(cells.z_weakest.abs()), 1.0)
    cells["prereg_sae_better"] = cells.ci_high_max < 0
    cells["prereg_sae_worse"] = cells.ci_low_min > 0
    cells["holm_reject"] = holm(cells.p_cell.to_numpy())
    d = pd.read_csv(SRC / "decisions.csv")
    d = d[d.metric == "got_refit_logistic_gap"][keys + ["cls", "sae_mean", "pca_value", "pca_k"]]
    cells = cells.merge(d, on=keys, how="left")
    assert (cells.prereg_sae_better == (cells.cls == "SAE BETTER")).all(), "rule mismatch"
    return cells


def write_table(cells: pd.DataFrame, summary: dict) -> str:
    rows = []
    for ref, name in (("error_matched", "Equal OWT error (existing reference)"),
                      ("capacity_k128", "Fixed $k=128$ (per-token active budget)"),
                      ("task_l0_matched", "$k$ = SAE's GoT task L0")):
        s = summary["counts"][ref]
        holm_txt = "--" if ref == "error_matched" else str(s["better_holm"])
        rows.append(f"{name} & {s['pca_k']} & {s['better']} & {holm_txt} & {s['inconclusive']} & {s['worse']} \\\\")
    better = cells[cells.prereg_sae_better & (cells.reference == "capacity_k128")]
    ex = []
    for _, r in better.sort_values(["layer", "family"]).iterrows():
        ex.append(f"L{r.layer} {LABEL[(r["family"], r["name"])]}: {r.sae_mean:.3f} vs {float(r.pca_value):.3f}")
    return "\n".join([
        "% generated by scripts/shared/pca_cm_posthoc_multiplicity.py from results/shared/pca_capacity_matched/",
        "\\begin{table}[t]", "\\centering", "\\small",
        "\\caption{PCA-CM (\\evlabel{validation}; GoT cities+neg\\_cities VAL, 448 rows): SAE vs PCA on the GoT "
        "re-fit logistic truth gap (lower is better) under three matching constraints, over the 20 trained "
        "family$\\times$layer cells (L8, L11; random decoder excluded). ``Better''/``worse'': every seed's paired 95\\,\\% "
        "grouped-bootstrap CI excludes zero (pre-registered rule, no correction across cells). ``Holm'': cells that "
        "also survive an approximate post-hoc Holm correction over the 40 capacity-matched cells. Better at $k=128$ "
        "(SAE vs PCA gap): " + "; ".join(ex) + ".}",
        "\\label{tab:pcacm}",
        "\\begin{adjustbox}{max width=\\linewidth}",
        "\\begin{tabular}{lccccc}", "\\toprule",
        "PCA reference & PCA $k$ & SAE better & of which Holm & inconclusive & SAE worse \\\\", "\\midrule",
        *rows, "\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table}", ""])


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s", force=True)
    for path in (OUT, TABLE):
        if path.exists():
            raise SystemExit(f"refusing to overwrite {path.relative_to(ROOT)}")
    cells = cell_table()
    d = pd.read_csv(SRC / "decisions.csv")
    d = d[(d.metric == "got_refit_logistic_gap") & (d.name != "topk_frozen_decoder")]
    counts = {}
    for ref in ("error_matched",) + REFS:
        q = d[d.reference == ref]
        ks = sorted({int(k) for v in q.pca_k.astype(str) for k in v.split(";")})
        c = {"better": int((q.cls == "SAE BETTER").sum()), "inconclusive": int((q.cls == "INCONCLUSIVE").sum()),
             "worse": int((q.cls == "SAE WORSE").sum()), "equivalent": int((q.cls == "EQUIVALENT").sum()),
             "pca_k": f"{ks[0]}--{ks[-1]}" if ks[0] != ks[-1] else str(ks[0])}
        if ref in REFS:
            cr = cells[cells.reference == ref]
            c["better_holm"] = int((cr.prereg_sae_better & cr.holm_reject).sum())
            c["seeds_individually_worse"] = int(
                (pd.read_csv(SRC / "got_paired.csv").query("reference == @ref and name != 'topk_frozen_decoder'")
                 .diff_refit_logistic_gap_ci_low > 0).sum())
        counts[ref] = c
    summary = {
        "evidence_level": "validation; post-hoc descriptive re-analysis (normal approximation to stored bootstrap CIs)",
        "n_cells_corrected": int(len(cells)), "alpha": ALPHA, "counts": counts,
        "holm_surviving_better_cells": cells[cells.prereg_sae_better & cells.holm_reject][
            ["layer", "family", "name", "reference"]].to_dict("records"),
        "conclusion": ("The pre-registered 'SAE BETTER' cells are nominal per-cell results without correction "
                       "across cells; only a subset survive Holm. Use 'better under the study's comparison "
                       "criterion', not 'significantly better'."),
    }
    OUT.mkdir(parents=True)
    cells.to_csv(OUT / "cells.csv", index=False)
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    TABLE.write_text(write_table(cells, summary))
    for ref, c in counts.items():
        log.info("%s: %s", ref, c)
    log.info("Holm-surviving better cells: %s", summary["holm_surviving_better_cells"])


if __name__ == "__main__":
    main()
