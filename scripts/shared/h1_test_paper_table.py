"""Paper table for H1-TEST (the single RepE-LM held-out TEST pass), from committed artifacts only.

Reads  results/repe/repe_lm_test_evaluation/{confirmatory_cells.csv,ht4_probe_transfer.json,comparisons.csv}
Writes research_paper/Latex/tables/t_h1test.tex (refuses to overwrite).

No metric is recomputed; values are formatted exactly as stored. Run from the repository root:
    python scripts/shared/h1_test_paper_table.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / 'results/repe/repe_lm_test_evaluation'
TABLE = ROOT / 'research_paper/Latex/tables/t_h1test.tex'

METRIC = {
    'm4__preservation_rec': r'$T_{\text{rec}}/T_{\text{full}}$ $\uparrow$',
    'rlm__pair_dir_cosine': r'pair-direction cosine $\uparrow$',
    'repe_persona__refit_logistic_gap': r'persona re-fit gap $\downarrow$',
}
NAME = {'C1': 'TopK', 'C2': 'ReLU', 'C3': 'BatchTopK vs JumpReLU'}


def load():
    cells = pd.read_csv(RES / 'confirmatory_cells.csv')
    ht4 = json.loads((RES / 'ht4_probe_transfer.json').read_text())
    comp = pd.read_csv(RES / 'comparisons.csv')
    return cells, ht4, comp


def fmt_p(p):
    return f'{p:.3f}' if p >= 1e-3 else f'{p:.1e}'.replace('e-0', 'e-')


def rows(cells):
    out, last = [], None
    for _, r in cells.iterrows():
        hyp = r.hypothesis if r.hypothesis != last else ''
        met = METRIC[r.metric] if r.hypothesis != last else ''
        last = r.hypothesis
        conf = r'\textbf{yes}' if r.confirmed_cell else 'no'
        out.append(
            f'{hyp} & {met} & {r.comparison} {NAME[r.comparison]} & L{int(r.layer)} & {r.val_diff:+.3f} & '
            f'{r.test_ref:.3f} $\\rightarrow$ {r.test_new:.3f} & {r.test_diff:+.3f} [{r.test_ci95_low:+.3f}, '
            f'{r.test_ci95_high:+.3f}] & {int(r.test_pairs_better)}/9 & {fmt_p(r.test_welch_p_holm)} & {conf} \\\\')
    return out


def verdicts(cells):
    return {h: bool(g.confirmed_cell.all()) for h, g in cells.groupby('hypothesis')}


def caption(cells, ht4, comp):
    v = verdicts(cells)
    word = {True: 'CONFIRMED', False: 'NOT CONFIRMED'}
    cls = comp.cls.value_counts()
    t78 = ', '.join(f"{L} {ht4[L]['test_only_T7_T8']['auroc']:.3f}" for L in ('L1', 'L8', 'L11'))
    n34 = ', '.join(f"{L} {ht4[L]['neutral_N3_N4']['auroc']:.3f}" for L in ('L1', 'L8', 'L11'))
    return (
        r'H1-TEST (\evlabel{test}; single RepE-LM held-out pass, 81 SAEs, 2,408 TEST rows; probes, directions and '
        r'sites fitted on TRAIN only). Diff = R2 minus old (3 vs 3 seeds, Welch 95\,\% CI, 9 cross-seed pairs). A cell '
        r'is confirmed only if all 9 pairs are better, the CI excludes 0 and the Welch $p$, Holm-adjusted over the 13 '
        r'cells, is $<0.05$; a hypothesis is confirmed only if all its cells are. '
        f"Verdicts: HT1 {word[v['HT1']]}, HT2 {word[v['HT2']]}, HT3 {word[v['HT3']]}. "
        f'HT4 (descriptive): persona-probe AUROC on test-only wording T7/T8: {t78}; '
        f'neutral N3/N4 floor (pre-registered $\\le$0.55): {n34}, so this negative control FAILS at L8 and L11. '
        f"Secondary comparisons (90 cells, exploratory, uncorrected, not in this table): "
        f"{cls.get('IMPROVEMENT', 0)} improvement, {cls.get('NO CLEAR CHANGE', 0)} no clear change, "
        f"{cls.get('REGRESSION', 0)} regression. "
        r'Source: \texttt{results/\allowbreak{}repe/\allowbreak{}repe\_lm\_test\_evaluation/}.')


def build(cells, ht4, comp):
    body = '\n'.join(rows(cells))
    return (
        '% generated by scripts/shared/h1_test_paper_table.py from results/repe/repe_lm_test_evaluation/\n'
        '\\begin{table}[t]\n\\centering\n\\small\n'
        f'\\caption{{{caption(cells, ht4, comp)}}}\n\\label{{tab:h1test}}\n'
        '\\begin{adjustbox}{max width=\\linewidth}\n\\begin{tabular}{lllccccccc}\n\\toprule\n'
        'Hyp. & Metric & Comparison & Layer & VAL diff & TEST old $\\rightarrow$ R2 & TEST diff [95\\,\\% CI] & '
        'pairs & Holm $p$ & confirmed \\\\\n\\midrule\n'
        f'{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{table}}\n')


def main():
    if TABLE.exists():
        raise SystemExit(f'{TABLE.relative_to(ROOT)} exists; refusing to overwrite')
    TABLE.write_text(build(*load()))
    print(f'wrote {TABLE.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
