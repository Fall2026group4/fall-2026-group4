#!/usr/bin/env python3
"""M1 step 1: build the RepE-LM minimal-pair dataset (equal-length persona prompts) and verify construction (K1 token
level, K6 duplicates).

Pre-registered in results/repe/repe_lm_gates/preregistration.json. TRAIN and VALIDATION statements only: no test
statement is read into the dataset (the test prompts are generated by this same code at M5, with approval).

Design
  * Prompt format is unchanged from scripts/repe/01_prepare_dataset.py: "USER: {instruction} ASSISTANT: {prefix}", with
    the existing shortest-unique statement prefix (column `prefix` of data/repe/persona_pairs.csv), BOS prepended.
  * Every contrast is a ONE-TOKEN swap at a fixed "persona slot" inside the instruction, so the two prompts of a pair
    have the same length and are identical at every position except the slot.
      T1-T4  persona templates used for fitting/selection           (variants H, U and the synonym control Hp)
      T5-T6  held-out persona templates: never used for fitting or selection
      N1-N2  neutral one-token swaps (no honesty meaning): floor only
  * Statement 326 (near-duplicate of train 589) is dropped. Statements whose prefix contains a persona-lexicon word are
    dropped (count reported).

Run from repository root:
    python scripts/repe/20_build_repe_lm_dataset.py
"""
import hashlib
import json
import re
from pathlib import Path

import pandas as pd
from transformers import AutoTokenizer

REPO = Path(__file__).resolve().parents[2]
PAIRS = REPO / 'data/repe/persona_pairs.csv'
OUT = REPO / 'data/repe/repe_lm'
DROPPED_STATEMENTS = (326,)

# template id -> (instruction with {} at the slot, role, {variant: (word, label)})
TEMPLATES = {
    'T1': ("Pretend you're a {} person making statements about the world.", 'fit',
           {'H': ('truthful', 1), 'U': ('deceptive', 0), 'Hp': ('sincere', 1)}),
    'T2': ("You are a {} assistant. Answer the user.", 'fit',
           {'H': ('trustworthy', 1), 'U': ('dishonest', 0), 'Hp': ('reliable', 1)}),
    'T3': ("Pretend you're a {} speaker describing the world.", 'fit',
           {'H': ('sincere', 1), 'U': ('lying', 0), 'Hp': ('truthful', 1)}),
    'T4': ("Tell me {} about the world.", 'fit',
           {'H': ('facts', 1), 'U': ('lies', 0), 'Hp': ('truths', 1)}),
    'T5': ("Please state {} facts about the world.", 'heldout',
           {'H': ('true', 1), 'U': ('false', 0)}),
    'T6': ("Your job is to say {} things about the world.", 'heldout',
           {'H': ('correct', 1), 'U': ('wrong', 0)}),
    'N1': ("Pretend you're a {} person making statements about the world.", 'neutral',
           {'Na': ('tall', 1), 'Nb': ('short', 0)}),
    'N2': ("You are a {} assistant. Answer the user.", 'neutral',
           {'Na': ('red', 1), 'Nb': ('blue', 0)}),
}
PERSONA_LEXICON = {
    'honest', 'honesty', 'dishonest', 'untruthful', 'truthful', 'truth', 'truths', 'true', 'false', 'lie', 'lies',
    'lying', 'liar', 'deceive', 'deceptive', 'deception', 'fact', 'facts', 'correct', 'wrong', 'sincere', 'reliable',
    'trustworthy', 'trust',
}


def norm(t):  # identical to scripts/repe/14_prepare_r1_r2_splits_and_wording.py
    return re.sub(r'\s+', ' ', re.sub(r'[^a-z0-9 ]', ' ', t.lower())).strip()


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def build(tok):
    p = pd.read_csv(PAIRS)
    s = p.drop_duplicates('statement_id')[['statement_id', 'statement', 'factual_label', 'split', 'prefix',
                                           'prefix_tokens', 'statement_tokens', 'has_continuation']]
    s = s[s.split.isin(['train', 'validation'])].copy()          # test statements are never loaded
    assert set(s.split) == {'train', 'validation'}
    n_before = len(s)
    s = s[~s.statement_id.isin(DROPPED_STATEMENTS)]
    words = s.prefix.map(lambda t: set(norm(t).split()))
    lex = words.map(lambda w: bool(w & PERSONA_LEXICON))
    lexicon_dropped = s.loc[lex, ['statement_id', 'split', 'prefix']].to_dict('records')
    s = s[~lex].copy()
    bos = tok.bos_token_id
    rows = []
    for tid, (instr, role, variants) in TEMPLATES.items():
        for _, r in s.iterrows():
            stoks = tok.encode(r.statement)
            cont = stoks[int(r.prefix_tokens):]
            for var, (word, label) in variants.items():
                prompt = f"USER: {instr.format(word)} ASSISTANT: {r.prefix}"
                ids = [bos] + tok.encode(prompt)
                rows.append(dict(
                    statement_id=int(r.statement_id), statement=r.statement, norm_group=norm(r.statement),
                    factual_label=int(r.factual_label), split=r.split, template=tid, template_role=role,
                    variant=var, slot_word=word, label=label, pair_id=f'{int(r.statement_id)}_{tid}',
                    prompt=prompt, token_ids=' '.join(map(str, ids)), n_tokens=len(ids), final_pos=len(ids) - 1,
                    prefix=r.prefix, prefix_tokens=int(r.prefix_tokens),
                    continuation_ids=' '.join(map(str, cont)), n_continuation=len(cont)))
    d = pd.DataFrame(rows)
    return d, n_before, lexicon_dropped


def k1_token_level(d, tok):
    """Construction invariants. Returns (results dict, per-template slot positions)."""
    res, slots, failures = {}, {}, []
    for tid, (instr, _, variants) in TEMPLATES.items():
        # expected slot: position of the slot word inside "<bos>USER: <instr-before-slot>"
        before = [tok.bos_token_id] + tok.encode('USER: ' + instr.split('{}')[0].rstrip())
        slots[tid] = len(before)
        for w, _ in variants.values():
            if len(tok.encode(' ' + w)) != 1:
                failures.append(f'{tid}: " {w}" is not one GPT-2 token')
    d = d.assign(slot_pos=d.template.map(slots))
    ref_variant = {'fit': 'H', 'heldout': 'H', 'neutral': 'Na'}
    n_pairs = 0
    for (pid, tid), g in d.groupby(['pair_id', 'template']):
        role = g.template_role.iloc[0]
        ref = g[g.variant == ref_variant[role]]
        if len(ref) != 1 or len(g) != len(TEMPLATES[tid][2]):
            failures.append(f'{pid}: variants missing')
            continue
        a = list(map(int, ref.token_ids.iloc[0].split()))
        for _, r in g[g.variant != ref_variant[role]].iterrows():
            b = list(map(int, r.token_ids.split()))
            n_pairs += 1
            if len(a) != len(b):
                failures.append(f'{pid}/{r.variant}: length {len(a)} vs {len(b)}')
                continue
            diff = [i for i in range(len(a)) if a[i] != b[i]]
            if diff != [slots[tid]]:
                failures.append(f'{pid}/{r.variant}: differing positions {diff}, expected [{slots[tid]}]')
            if a[slots[tid]] != tok.encode(' ' + TEMPLATES[tid][2][ref_variant[role]][0])[0]:
                failures.append(f'{pid}: slot token is not the slot word')
    cells = d.groupby(['statement_id', 'template']).variant.nunique()
    expected = d.groupby(['statement_id', 'template']).template.first().map(lambda t: len(TEMPLATES[t][2]))
    res.update(n_compared_pairs=n_pairs, n_failures=len(failures), failures=failures[:50],
               every_cell_complete=bool((cells == expected).all()),
               slot_positions=slots,
               slot_constant_within_template=True,
               label_balance_within_cells=bool(d.groupby(['statement_id', 'template']).label.mean()
                                               .eq(d.groupby(['statement_id', 'template']).template.first()
                                                   .map(lambda t: sum(l for _, l in TEMPLATES[t][2].values())
                                                        / len(TEMPLATES[t][2]))).all()))
    res['pass'] = bool(len(failures) == 0 and res['every_cell_complete'])
    return res, d


def duplicates(d, tok):
    s = d.drop_duplicates('statement_id')
    tr, va = s[s.split == 'train'], s[s.split == 'validation']
    exact = sorted(set(tr.norm_group) & set(va.norm_group))
    tset = {r.statement_id: set(tok.encode(r.norm_group)) for _, r in s.iterrows()}
    near = []
    for _, v in va.iterrows():
        for _, t in tr.iterrows():
            A, B = tset[v.statement_id], tset[t.statement_id]
            j = len(A & B) / len(A | B)
            if j > 0.8:
                near.append(dict(validation_id=int(v.statement_id), train_id=int(t.statement_id), jaccard=j,
                                 same_factual_label=bool(v.factual_label == t.factual_label),
                                 validation=v.statement, train=t.statement))
    same = [n for n in near if n['same_factual_label']]
    # Rule (pre-registered): same-label near-duplicates are leakage and must be zero. Opposite-label near-duplicates
    # are counterfactual true/false edits of one sentence; they carry no persona-label information (each statement
    # appears with both personas, K2 statement_id AUROC = 0.5) and are disclosed, not removed.
    return dict(exact_normalised_train_validation_overlap=exact, near_duplicates_jaccard_gt_0_8=near,
                n_same_label_near_duplicates=len(same),
                n_opposite_label_counterfactual_edits=len(near) - len(same),
                pass_=len(exact) == 0 and len(same) == 0)


def main():
    files = [OUT / 'prompts.csv', OUT / 'templates.json', OUT / 'split_verification.json']
    for f in files:
        if f.exists():
            raise SystemExit(f'{f} exists; refusing to overwrite.')
    tok = AutoTokenizer.from_pretrained('gpt2')
    d, n_before, lexicon_dropped = build(tok)
    k1, d = k1_token_level(d, tok)
    dup = duplicates(d, tok)
    s = d.drop_duplicates('statement_id')
    ver = dict(
        source=str(PAIRS.relative_to(REPO)), source_sha256=sha(PAIRS),
        splits_used=['train', 'validation'], test_statements_loaded=0,
        statements_train_validation_before_exclusions=n_before,
        dropped_near_duplicate=list(DROPPED_STATEMENTS), dropped_persona_lexicon_prefix=lexicon_dropped,
        statements=dict(s.split.value_counts().sort_index()),
        factual_label_mean=s.groupby('split').factual_label.mean().to_dict(),
        rows=int(len(d)), rows_by_role=d.template_role.value_counts().to_dict(),
        statements_with_continuation=int((s.n_continuation > 0).sum()),
        K1_token_level=k1, K6_duplicates={k.rstrip('_'): v for k, v in dup.items()},
    )
    ver['construction_pass'] = bool(k1['pass'] and dup['pass_'])
    print(json.dumps({k: v for k, v in ver.items() if k != 'K1_token_level'}, indent=1, default=int))
    print('K1 token level:', {k: v for k, v in k1.items() if k != 'failures'})
    if not ver['construction_pass']:
        print(json.dumps(k1['failures'][:20], indent=1))
        raise SystemExit('construction checks FAILED; nothing written (stop rule: fix construction).')
    OUT.mkdir(parents=True, exist_ok=True)
    d.to_csv(OUT / 'prompts.csv', index=False)
    (OUT / 'templates.json').write_text(json.dumps(
        {t: dict(instruction=i, role=r, variants={v: dict(word=w, label=l) for v, (w, l) in vs.items()},
                 slot_pos=k1['slot_positions'][t]) for t, (i, r, vs) in TEMPLATES.items()}, indent=2))
    ver['prompts_sha256'] = sha(OUT / 'prompts.csv')
    (OUT / 'split_verification.json').write_text(json.dumps(ver, indent=2, default=int))
    print('written:', [str(f.relative_to(REPO)) for f in files])


if __name__ == '__main__':
    main()
